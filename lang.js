const LANG_KEY = "lang";

function getValue(dict, key) {
  return key.split(".").reduce((acc, part) => (acc ? acc[part] : undefined), dict);
}

function applyDictionary(dict) {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = getValue(dict, el.dataset.i18n);
    if (value !== undefined) el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const value = getValue(dict, el.dataset.i18nAria);
    if (value !== undefined) el.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const value = getValue(dict, el.dataset.i18nPlaceholder);
    if (value !== undefined) el.setAttribute("placeholder", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const value = getValue(dict, el.dataset.i18nAlt);
    if (value !== undefined) el.setAttribute("alt", value);
  });
}

function setLanguage(lang) {
  const next = I18N[lang] ? lang : "en";
  applyDictionary(I18N[next]);
  document.documentElement.lang = next;

  const toggle = document.querySelector(".lang-toggle");
  if (toggle) {
    const label = toggle.querySelector(".lang-label");
    if (label) label.textContent = next.toUpperCase();
    const nextLabel = next === "vi" ? "Chuyen sang EN" : "Switch to VI";
    toggle.setAttribute("aria-label", nextLabel);
    toggle.setAttribute("title", nextLabel);
  }

  try {
    localStorage.setItem(LANG_KEY, next);
  } catch (error) {
    // Ignore storage failures.
  }
}

function getInitialLang() {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored && I18N[stored]) return stored;
  } catch (error) {
    // Ignore storage failures.
  }
  const navLang = (navigator.language || "").toLowerCase();
  return navLang.startsWith("vi") ? "vi" : "en";
}

const toggleBtn = document.querySelector(".lang-toggle");
if (toggleBtn) {
  toggleBtn.addEventListener("click", () => {
    const current = document.documentElement.lang === "vi" ? "vi" : "en";
    setLanguage(current === "vi" ? "en" : "vi");
  });
}

setLanguage(getInitialLang());
